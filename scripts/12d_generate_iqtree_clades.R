#!/usr/bin/env Rscript

# ==============================================================================
# Script 12D: AUTO-GENERATE CLADES FROM IQ-TREE CORE PHYLOGENY (BOOTSTRAP FILTERED)
# Purpose:
#   1. Load IQ-TREE treefile for 704 E. coli core isolates
#   2. Filter/collapse internal branches with bootstrap support below threshold
#   3. Compute pairwise patristic distance matrix (substitutions/site)
#   4. Perform complete-linkage clustering at defined distance threshold(s)
#   5. Normalize tip IDs to match metadata/iTOL standard
#   6. Export clade mapping CSV, clade counts, and an iTOL colorstrip
# ==============================================================================

suppressPackageStartupMessages({
  library(ape)
  library(readr)
  library(dplyr)
  library(stringr)
})

message("=== SCRIPT 12D: GENERATING CLADES FROM IQ-TREE CORE PHYLOGENY ===")

# --- Configuration & File Paths ---
tree_file <- "/home/samuelajulo/epi/Ecoli_epi/results/12c_all_preharvest_combined/iqtree/all_preharvest_704_core_phylo.treefile"
out_dir   <- "/home/samuelajulo/epi/Ecoli_epi/results/12d_clade_analysis"

# Patristic distance threshold (substitutions per site)
DIST_THRESHOLD <- 0.0002

# Minimum bootstrap support threshold (%)
MIN_BOOTSTRAP  <- 95

# Allow command line overrides: Rscript script.R [DIST_THRESHOLD] [MIN_BOOTSTRAP]
args <- commandArgs(trailingOnly = TRUE)
if (length(args) >= 1) DIST_THRESHOLD <- as.numeric(args[1])
if (length(args) >= 2) MIN_BOOTSTRAP  <- as.numeric(args[2])

dir.create(out_dir, recursive = TRUE, showWarnings = FALSE)

if (!file.exists(tree_file)) {
  stop("[ERROR] Tree file not found: ", tree_file, call. = FALSE)
}

# --- 1. Load Tree & Process Bootstrap Support ---
message("[INFO] Reading tree file...")
tree <- read.tree(tree_file)
num_tips <- length(tree$tip.label)
message("[INFO] Total tips in tree: ", num_tips)

# Parse IQ-TREE bootstrap values (supports "100" or dual formats like "95/100")
parse_bootstrap <- function(lbl) {
  if (is.na(lbl) || lbl == "") return(NA_real_)
  parts <- unlist(strsplit(as.character(lbl), "/"))
  suppressWarnings(as.numeric(parts[length(parts)]))
}

bs_values <- sapply(tree$node.label, parse_bootstrap)
valid_bs  <- bs_values[!is.na(bs_values)]

tree_filtered <- tree

if (length(valid_bs) > 0) {
  pass_count <- sum(valid_bs >= MIN_BOOTSTRAP)
  pct_pass   <- (pass_count / length(valid_bs)) * 100
  message(sprintf("[INFO] Bootstrap threshold: >= %g%% (%d / %d internal nodes pass, %.1f%%)",
                  MIN_BOOTSTRAP, pass_count, length(valid_bs), pct_pass))

  # Find internal nodes below support threshold (node index in ape = num_tips + node_id)
  low_bs_idx   <- which(!is.na(bs_values) & bs_values < MIN_BOOTSTRAP)
  low_bs_nodes <- low_bs_idx + num_tips

  # Collapse branches leading into low-support nodes to length 0
  low_bs_edges <- which(tree_filtered$edge[, 2] %in% low_bs_nodes)
  if (length(low_bs_edges) > 0) {
    tree_filtered$edge.length[low_bs_edges] <- 0
    message(sprintf("[INFO] Collapsed %d weak internal branches (length set to 0).", length(low_bs_edges)))
  }
} else {
  message("[WARNING] No numeric bootstrap labels found in treefile. Using unweighted branch lengths.")
}

# --- 2. Compute Patristic Distances & Cluster ---
message("[INFO] Calculating patristic distance matrix using 'ape::cophenetic'...")
patristic_dist <- cophenetic(tree_filtered)

message("[INFO] Clustering tips with max distance threshold = ", DIST_THRESHOLD, " ...")
hc <- hclust(as.dist(patristic_dist), method = "complete")
clusters <- cutree(hc, h = DIST_THRESHOLD)

# --- 3. Normalize Tip IDs ---
normalize_tip_id <- function(x) {
  x <- as.character(x)
  x <- basename(x)
  x <- str_remove(x, "\\.gz$")
  x <- str_remove(x, "\\.(fasta|fna|fa|gff|gff3)$")
  accession_like <- str_extract(x, "GC[AF]_[0-9]+\\.[0-9]+")
  ifelse(is.na(accession_like), x, accession_like)
}

clade_df <- tibble(
  Raw_Tip_ID = names(clusters),
  Tip_ID     = normalize_tip_id(names(clusters)),
  Clade_Num  = unname(clusters)
) %>%
  mutate(Clade = paste0("Clade_", sprintf("%03d", Clade_Num))) %>%
  select(Tip_ID, Clade, Raw_Tip_ID)

# --- 4. Color Assignment for iTOL ---
unique_clades <- sort(unique(clade_df$Clade))
n_clades <- length(unique_clades)
message("[INFO] Auto-generated ", n_clades, " clades.")

# Generate high-contrast colors across HCL spectrum
hues <- seq(15, 375, length.out = n_clades + 1)[1:n_clades]
clade_colors <- hcl(h = hues, c = 85, l = 55)

color_map <- tibble(
  Clade = unique_clades,
  Color = clade_colors
)

clade_df <- clade_df %>% left_join(color_map, by = "Clade")

# --- 5. Export iTOL Dataset Colorstrip ---
itol_file <- file.path(out_dir, "itol_autogenerated_clades_colorstrip.txt")
con <- file(itol_file, open = "wt")

writeLines("DATASET_COLORSTRIP", con)
writeLines("SEPARATOR TAB", con)
writeLines(paste("DATASET_LABEL", paste0("Clades_d", DIST_THRESHOLD, "_bs", MIN_BOOTSTRAP), sep = "\t"), con)
writeLines("COLOR\t#000000", con)
writeLines("STRIP_WIDTH\t40", con)
writeLines("MARGIN\t5", con)
writeLines("BORDER_WIDTH\t1", con)
writeLines("BORDER_COLOR\t#000000", con)
writeLines("SHOW_INTERNAL\t0", con)

writeLines(paste("LEGEND_TITLE", "Auto-generated Clades", sep = "\t"), con)
writeLines(paste(c("LEGEND_SHAPES", rep("1", n_clades)), collapse = "\t"), con)
writeLines(paste(c("LEGEND_COLORS", color_map$Color), collapse = "\t"), con)
writeLines(paste(c("LEGEND_LABELS", color_map$Clade), collapse = "\t"), con)

writeLines("DATA", con)
apply(clade_df, 1, function(row) {
  writeLines(paste(row[["Tip_ID"]], row[["Color"]], row[["Clade"]], sep = "\t"), con)
})
close(con)

# --- 6. Export Output Tables ---
csv_out <- file.path(out_dir, "all_preharvest_704_clades.csv")
write_csv(clade_df %>% select(Tip_ID, Clade, Color, Raw_Tip_ID), csv_out)

counts_out <- file.path(out_dir, "clade_summary_counts.csv")
clade_counts <- clade_df %>% count(Clade, name = "Isolate_Count", sort = TRUE)
write_csv(clade_counts, counts_out)

message("[SUCCESS] Output files generated:")
message("  - Clade Table: ", csv_out)
message("  - Summary Counts: ", counts_out)
message("  - iTOL Annotation: ", itol_file)

message("\nTop 10 Largest Clades:")
print(head(clade_counts, 10))
