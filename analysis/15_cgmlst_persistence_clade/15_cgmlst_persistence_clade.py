#!/usr/bin/env python3
"""
15_cgmlst_persistence_clade.py

Reconstruct HC10/HC20/HC50 from a cgMLST allele matrix, classify temporal
behavior using the same rules as the existing 14B livestock workflow,
test whether persistent-like clusters are concentrated in specific core-SNP
clades, and generate iTOL annotation strips for the livestock IQ-TREE.

Required inputs in --input-dir:
  metadata_704.csv
  cgMLST95.tsv

Optional inputs:
  all_preharvest_704_clades.csv
  itol_autogenerated_clades_colorstrip.txt
  all_preharvest_704_core_phylo.treefile

If the clade CSV is absent, the bundled iTOL clade colorstrip is parsed.
"""

from __future__ import annotations
import argparse
import colorsys
import math
import os
import re
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.cluster.hierarchy import linkage, fcluster
from scipy.spatial.distance import pdist, squareform
from scipy.stats import fisher_exact

THRESHOLDS = {"HC10": 10, "HC20": 20, "HC50": 50}
TEMPORAL_LEVELS = [
    "Persistent-like",
    "Emerging-like",
    "Re-emergence-like / unsampled persistence",
    "Repeated detection, limited temporal evidence",
    "Sporadic/minority",
    "Unknown year",
]
TEMPORAL_COLORS = {
    "Persistent-like": "#E69F00",
    "Emerging-like": "#0072B2",
    "Re-emergence-like / unsampled persistence": "#009E73",
    "Repeated detection, limited temporal evidence": "#CC79A7",
    "Sporadic/minority": "#999999",
    "Unknown year": "#D9D9D9",
}

def accession_root(x):
    x = os.path.basename(str(x))
    m = re.search(r"(GC[AF]_[0-9]+)(?:\.[0-9]+)?", x)
    if m:
        return m.group(1)
    x = re.sub(r"\.(fasta|fna|fa|faa|ffn|gff|gff3|aln|tsv|csv|gz)$", "", x)
    return x.strip()

def pick_col(df, candidates):
    for c in candidates:
        if c in df.columns:
            return c
    return None

def extract_year(x):
    if pd.isna(x):
        return np.nan
    m = re.search(r"(18|19|20)[0-9]{2}", str(x))
    return int(m.group(0)) if m else np.nan

def parse_allele(v):
    if pd.isna(v):
        return -1
    s = str(v).strip()
    if s == "" or s.upper() in {"NA","NAN","-","?","LNF","NIPH","NIPHEM","PLOT3","PLOT5","LOTSC","ASM","ALM"}:
        return -1
    m = re.match(r"^(?:INF-)?([0-9]+)$", s)
    if not m:
        return -1
    z = int(m.group(1))
    return z if z > 0 else -1

def allele_distance(u, v):
    valid = (u > 0) & (v > 0)
    if not np.any(valid):
        return float(len(u))
    return float(np.sum(u[valid] != v[valid]))

def stable_labels(raw, ids, prefix):
    tmp = pd.DataFrame({"raw": raw, "id": ids})
    order = (tmp.groupby("raw")
             .agg(n=("id","size"), min_id=("id","min"))
             .sort_values(["n","min_id"], ascending=[False,True])
             .reset_index())
    mapping = {row.raw: f"{prefix}_{i+1:03d}" for i, row in order.iterrows()}
    return [mapping[x] for x in raw]

def longest_run(years):
    years = sorted(set(int(y) for y in years if not pd.isna(y)))
    if not years:
        return 0
    best = cur = 1
    for a, b in zip(years[:-1], years[1:]):
        cur = cur + 1 if b == a + 1 else 1
        best = max(best, cur)
    return best

def longest_gap(years):
    years = sorted(set(int(y) for y in years if not pd.isna(y)))
    if len(years) < 2:
        return 0
    return int(max(np.diff(years)) - 1)

def classify(row, study_first, study_last):
    n = int(row.N_genomes)
    yd = int(row.Years_detected)
    span = row.Year_span
    gap = int(row.Longest_detection_gap)
    consecutive = int(row.Consecutive_years_detected)
    first = row.First_year
    last = row.Last_year

    if pd.isna(first) or pd.isna(last):
        return "Unknown year"

    total_span = max(1, int(study_last - study_first))
    late_start_cutoff = study_last - max(2, math.ceil(total_span * 0.25))

    if n <= 2 or yd <= 1:
        return "Sporadic/minority"
    if first >= late_start_cutoff and n >= 3 and yd >= 2:
        return "Emerging-like"
    if gap >= 5 and span >= 5 and yd >= 2:
        return "Re-emergence-like / unsampled persistence"
    if n >= 5 and span >= 5 and yd >= 3 and consecutive >= 2:
        return "Persistent-like"
    if n >= 3 and yd >= 2:
        return "Repeated detection, limited temporal evidence"
    return "Sporadic/minority"

def bh_adjust(pvals):
    p = np.asarray(pvals, dtype=float)
    n = len(p)
    if n == 0:
        return p
    order = np.argsort(p)
    ranked = p[order]
    q = ranked * n / np.arange(1, n + 1)
    q = np.minimum.accumulate(q[::-1])[::-1]
    q = np.clip(q, 0, 1)
    out = np.empty(n)
    out[order] = q
    return out

def palette(labels):
    labels = sorted(set(str(x) for x in labels))
    out = {}
    n = max(1, len(labels))
    for i, lab in enumerate(labels):
        h = i / n
        r, g, b = colorsys.hsv_to_rgb(h, 0.65, 0.85)
        out[lab] = "#{:02X}{:02X}{:02X}".format(int(r*255), int(g*255), int(b*255))
    return out

def write_itol(path, label, mapping, value_col, color_map):
    rows = mapping[["Tip_ID", value_col]].dropna().drop_duplicates("Tip_ID")
    values = [v for v in rows[value_col].astype(str).unique() if v in color_map]
    with open(path, "w") as fh:
        fh.write("DATASET_COLORSTRIP\n")
        fh.write("SEPARATOR TAB\n")
        fh.write(f"DATASET_LABEL\t{label}\n")
        fh.write("COLOR\t#000000\n")
        fh.write("STRIP_WIDTH\t35\n")
        fh.write("MARGIN\t3\n")
        fh.write("BORDER_WIDTH\t0\n")
        if values:
            fh.write("LEGEND_TITLE\t" + label + "\n")
            fh.write("LEGEND_SHAPES\t" + "\t".join(["1"]*len(values)) + "\n")
            fh.write("LEGEND_COLORS\t" + "\t".join(color_map[v] for v in values) + "\n")
            fh.write("LEGEND_LABELS\t" + "\t".join(values) + "\n")
        fh.write("DATA\n")
        for _, r in rows.iterrows():
            val = str(r[value_col])
            if val in color_map:
                fh.write(f"{r.Tip_ID}\t{color_map[val]}\t{val}\n")

def parse_itol_clades(path):
    rows = []
    in_data = False
    with open(path) as fh:
        for line in fh:
            line = line.rstrip("\n")
            if line == "DATA":
                in_data = True
                continue
            if not in_data or not line.strip():
                continue
            parts = line.split("\t")
            if len(parts) >= 3:
                rows.append((parts[0], parts[2], parts[1]))
    return pd.DataFrame(rows, columns=["Tip_ID","Clade","Clade_Color"])

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--input-dir", default="inputs")
    ap.add_argument("--output-dir", default="outputs")
    args = ap.parse_args()

    inp = Path(args.input_dir)
    out = Path(args.output_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "itol").mkdir(exist_ok=True)

    meta_path = inp / "metadata_704.csv"
    cg_path = inp / "cgMLST95.tsv"
    clade_csv = inp / "all_preharvest_704_clades.csv"
    clade_itol = inp / "itol_autogenerated_clades_colorstrip.txt"

    if not meta_path.exists():
        raise SystemExit(f"Missing required input: {meta_path}")
    if not cg_path.exists():
        raise SystemExit(f"Missing required input: {cg_path}")

    meta = pd.read_csv(meta_path)
    id_col = pick_col(meta, ["Assembly","Tip_ID","Isolate","Sample","sample"])
    if id_col is None:
        raise SystemExit("Could not detect genome/accession column in metadata.")
    year_col = pick_col(meta, ["Collection_year","Collection year","collection_year","Year","year","Collection date","collection_date"])
    if year_col is None:
        candidates = [c for c in meta.columns if "year" in c.lower() or "date" in c.lower()]
        year_col = candidates[0] if candidates else None
    if year_col is None:
        raise SystemExit("Could not detect collection year/date column in metadata.")

    meta["Accession_root"] = meta[id_col].map(accession_root)
    meta["Numeric_Year"] = meta[year_col].map(extract_year)
    meta = meta.drop_duplicates("Accession_root")

    if clade_csv.exists():
        clades = pd.read_csv(clade_csv)
        if "Tip_ID" not in clades.columns or "Clade" not in clades.columns:
            raise SystemExit("Clade CSV must contain Tip_ID and Clade.")
        clades = clades[["Tip_ID","Clade"]].copy()
    elif clade_itol.exists():
        clades = parse_itol_clades(clade_itol)[["Tip_ID","Clade"]]
    else:
        raise SystemExit("Need either all_preharvest_704_clades.csv or itol_autogenerated_clades_colorstrip.txt")

    clades["Accession_root"] = clades["Tip_ID"].map(accession_root)
    clades = clades.drop_duplicates("Accession_root")

    cg = pd.read_csv(cg_path, sep="\t", index_col=0)
    cg.index = [accession_root(x) for x in cg.index]
    cg = cg[~pd.Index(cg.index).duplicated(keep="first")]

    roots = sorted(set(meta.Accession_root) & set(clades.Accession_root) & set(cg.index))
    print(f"[INFO] Common genomes: {len(roots)}")
    if len(roots) < 2:
        raise SystemExit("Fewer than two genomes overlap across metadata, clades and cgMLST.")

    raw = cg.loc[roots]
    enc = raw.apply(lambda col: col.map(parse_allele)).astype(np.int32)
    arr = enc.values

    print("[INFO] Computing pairwise allele distances...")
    condensed = pdist(arr, metric=allele_distance)
    Z = linkage(condensed, method="single")

    assign = pd.DataFrame({"Accession_root": roots})
    for level, threshold in THRESHOLDS.items():
        labels = fcluster(Z, t=threshold, criterion="distance")
        assign[level] = stable_labels(labels, roots, level)

    analysis = (meta.merge(clades[["Accession_root","Tip_ID","Clade"]], on="Accession_root", how="inner")
                    .merge(assign, on="Accession_root", how="inner"))
    analysis.to_csv(out / "genome_level_hc_assignments.csv", index=False)

    valid = analysis.Numeric_Year.dropna().astype(int)
    if valid.empty:
        raise SystemExit("No valid collection years after parsing.")
    study_first, study_last = valid.min(), valid.max()

    all_cluster_summaries = []
    all_genome_temporal = []
    all_enrichment = []
    all_clade_genome = []

    for level in THRESHOLDS:
        def summarize(g):
            years = sorted(set(int(x) for x in g.Numeric_Year.dropna()))
            first = min(years) if years else np.nan
            last = max(years) if years else np.nan
            return pd.Series({
                "N_genomes": g.Accession_root.nunique(),
                "First_year": first,
                "Last_year": last,
                "Year_span": (last-first) if years else np.nan,
                "Years_detected": len(years),
                "Detected_years": ";".join(map(str, years)),
                "Longest_detection_gap": longest_gap(years),
                "Consecutive_years_detected": longest_run(years),
            })

        cs = (analysis.groupby(["Clade",level], dropna=False)
                     .apply(summarize)
                     .reset_index()
                     .rename(columns={level:"cgMLST_cluster"}))
        cs["HC_level"] = level
        cs["Temporal_category"] = cs.apply(lambda r: classify(r, study_first, study_last), axis=1)
        all_cluster_summaries.append(cs)

        gm = analysis.merge(
            cs[["Clade","cgMLST_cluster","Temporal_category"]].rename(columns={"cgMLST_cluster":level}),
            on=["Clade",level], how="left"
        )
        gm["HC_level"] = level
        all_genome_temporal.append(gm)

        # Descriptive burden by clade at genome level
        burden = (gm.groupby(["Clade","Temporal_category"])
                    .size().reset_index(name="Genome_count"))
        totals = gm.groupby("Clade").size().reset_index(name="Clade_total_genomes")
        burden = burden.merge(totals, on="Clade")
        burden["Percent_of_clade"] = 100 * burden.Genome_count / burden.Clade_total_genomes
        burden["HC_level"] = level
        all_clade_genome.append(burden)

        # Cluster-level Fisher test: persistent-like vs other clusters, clade vs all other clades
        tests = []
        clades_here = sorted(cs.Clade.unique())
        for cl in clades_here:
            in_cl = cs.Clade.eq(cl)
            pers = cs.Temporal_category.eq("Persistent-like")
            a = int((in_cl & pers).sum())
            b = int((in_cl & ~pers).sum())
            c = int((~in_cl & pers).sum())
            d = int((~in_cl & ~pers).sum())
            odds, p = fisher_exact([[a,b],[c,d]], alternative="two-sided")
            if not np.isfinite(p):
                p = 1.0
            tests.append({
                "HC_level": level,
                "Clade": cl,
                "Persistent_clusters_in_clade": a,
                "Other_clusters_in_clade": b,
                "Persistent_clusters_elsewhere": c,
                "Other_clusters_elsewhere": d,
                "Odds_ratio": odds,
                "P_value": p,
            })
        testdf = pd.DataFrame(tests)
        testdf["FDR_BH"] = bh_adjust(testdf.P_value.values)
        all_enrichment.append(testdf)

        # iTOL strips
        hc_colors = palette(gm[level].astype(str).unique())
        write_itol(out / "itol" / f"itol_{level}_colorstrip.txt",
                   level, gm.rename(columns={"Accession_root":"_root"}), level, hc_colors)
        write_itol(out / "itol" / f"itol_temporal_category_{level}.txt",
                   f"Temporal_{level}", gm, "Temporal_category", TEMPORAL_COLORS)

    cluster_summary = pd.concat(all_cluster_summaries, ignore_index=True)
    genome_temporal = pd.concat(all_genome_temporal, ignore_index=True)
    clade_burden = pd.concat(all_clade_genome, ignore_index=True)
    enrichment = pd.concat(all_enrichment, ignore_index=True)

    cluster_summary.to_csv(out / "cluster_temporal_summary_HC10_HC20_HC50.csv", index=False)
    genome_temporal.to_csv(out / "genome_temporal_assignments_HC10_HC20_HC50.csv", index=False)
    clade_burden.to_csv(out / "clade_temporal_genome_burden.csv", index=False)
    enrichment.to_csv(out / "clade_persistence_enrichment_cluster_level.csv", index=False)

    # Core-SNP clade strip from current assignments
    clade_colors = palette(analysis.Clade.astype(str).unique())
    write_itol(out / "itol" / "itol_coreSNP_clades_colorstrip.txt",
               "Core_SNP_clade", analysis, "Clade", clade_colors)

    # Console summary
    print("\n=== Persistent-like cluster summary ===")
    pers = cluster_summary[cluster_summary.Temporal_category.eq("Persistent-like")]
    if pers.empty:
        print("No persistent-like clusters at any tested HC level.")
    else:
        print(pers.groupby(["HC_level","Clade"]).agg(
            Persistent_clusters=("cgMLST_cluster","nunique"),
            Persistent_genomes=("N_genomes","sum")
        ).reset_index().to_string(index=False))

    print("\n=== FDR-significant clade enrichment ===")
    sig = enrichment[enrichment.FDR_BH <= 0.05].sort_values(["HC_level","FDR_BH"])
    print(sig.to_string(index=False) if len(sig) else "None at FDR <= 0.05.")

    print("\n[SUCCESS] Outputs written to:", out)

if __name__ == "__main__":
    main()
